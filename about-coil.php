                                            <strong>What is COIL?</strong><br>
                                            Collaborative Online International Learning (COIL) is an innovative teaching and learning paradigm that embeds international, multicultural experiences directly into the academic curriculum. Without requiring physical travel, COIL connects GIMS classes with classrooms at partner institutions worldwide, utilizing online communication tools to facilitate collaborative project-based learning.
                                            <br><br>
                                            <strong>How COIL Works at GIMS:</strong>
                                            <br><br>
                                            1. <strong>Co-Designed Curricula:</strong> Professors from GIMS and an international partner university co-create a joint syllabus or a specific course module where students from both institutions collaborate.
                                            <br><br>
                                            2. <strong>Virtual Cross-Border Teams:</strong> Students are assigned to multicultural teams, working across different time zones, languages, and cultures to solve business simulations, marketing case studies, or design challenges.
                                            <br><br>
                                            3. <strong>Collaborative Platforms:</strong> Teams use tools like Zoom, Microsoft Teams, Slack, and Miro to brainstorm, discuss projects, and present their findings to a joint panel of international judges.
                                            <br><br>
                                            <strong>Benefits of the COIL Pedagogy:</strong>
                                            <br><br>
                                            - <strong>Global Accessibility:</strong> Provides all GIMS students, regardless of background or financial resources, with valuable international experience.
                                            <br><br>
                                            - <strong>Virtual Collaboration Skills:</strong> Teaches students how to operate effectively in remote work environments, a critical capability for modern multinational corporations.
                                            <br><br>
                                            - <strong>Cross-Cultural Fluency:</strong> Builds intercultural communication, empathy, and negotiation skills through hands-on practice.
                                            <br><br>
                                            At GIMS, COIL is not just an extracurricular project—it is built directly into our PGDM program, helping our students gain the competitive edge needed in today's global market.
