                                                    <h5>Brief Report</h5>
                                                    <p>
                                                        The COIL 2.0 (Collaborative Online International Learning)
                                                        program brought together students from India and Russia for a
                                                        live international business simulation project focused on
                                                        identifying feasible trade opportunities between the two
                                                        countries.
                                                    </p>
                                                    <p>
                                                        The first session held on 1st November 2025 served as an
                                                        icebreaker and orientation where students were introduced to the
                                                        objective of the project, structure of collaboration, and team
                                                        allocation. Each team independently selected a research topic
                                                        related to the import and export of a specific product. With
                                                        mutual understanding and collaborative agreement, the teams then
                                                        commenced joint research activities under the COIL 2.0
                                                        framework.
                                                    </p>
                                                    <p>
                                                        The second session held on 15th November 2025 was focused on
                                                        deeper research and intercultural exchange. Teams discussed
                                                        product feasibility, trade policies, market demand, and
                                                        challenges. Teams also examined tariff structures, logistics,
                                                        sustainability, and government regulations. During the second
                                                        session, the teams delivered presentations on their respective
                                                        research topics. Based on the observations and feedback provided
                                                        by subject experts and faculty members, the identified gaps and
                                                        limitations were highlighted, and the teams were instructed to
                                                        address and refine them in subsequent stages of the research.
                                                    </p>
                                                    <p>
                                                        The final session on 15th December 2025, 16th December 2025 was
                                                        dedicated to final presentations. In the final stage of the
                                                        program, concluding presentations were conducted by each team.
                                                        These presentations reflected effective team collaboration,
                                                        sustained effort, and sincere commitment throughout the research
                                                        process. The final outcomes were presented before industry
                                                        experts and faculty members, who acknowledged and appreciated
                                                        the teams' analytical depth, collaborative approach, and overall
                                                        performance.
                                                    </p>
                                                    <p>
                                                        In the concluding session, each group presented their findings
                                                        before a panel of esteemed industry experts:<br />
                                                        - <strong>Mr. Pankaj Deol</strong>
                                                    </p>
                                                    <p>
                                                        The project emphasized not just business analysis but global
                                                        teamwork, respect for cultural diversity, and the importance of
                                                        international cooperation in trade.
                                                    </p>

