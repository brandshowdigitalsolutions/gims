                                        <p>GNIOT Institute of Management Studies (GIMS) follows a structured, dynamic, and stakeholder-informed approach to curriculum design and revision, ensuring that the Post Graduate Diploma in Management (PGDM) program remains academically rigorous, professionally relevant, and aligned with national and international educational standards.</p>
                                        
                                        <p>The curriculum is continuously reviewed and updated to meet emerging industry needs, global academic trends, and regulatory expectations. The process of curriculum revision is led by the Area Chairs, who collaborate with internal faculty, alumni, recruiters, industry professionals, and academic experts from reputed institutions across India and abroad.</p>
                                        
                                        <p>Sources of information for curriculum development include insights from the Corporate & Area Academic Advisory Boards, which comprise distinguished academicians, senior corporate leaders, and accomplished alumni. These boards play a key role in offering feedback based on current industry practices and evolving business challenges.</p>
                                        
                                        <p>Benchmarking with top B-schools, including IIMs and globally recognized institutions, also contributes to keeping the curriculum contemporary and competitive. Annual International Conferences hosted by the Institute offer additional insights into global management education practices and pedagogy innovations.</p>
                                        
                                        <p>Collaborations with overseas B-Schools and international accreditation bodies provide critical inputs regarding global trends and standards in business education. Further, AICTE's model PGDM curriculum and the guiding principles of the National Education Policy (NEP) 2020 serve as regulatory frameworks that inform curriculum structure, credit distribution, and course diversity.</p>
                                        
                                        <p>Internal curriculum reviews are conducted under the supervision of the Dean Academics, in consultation with the Director. These reviews evaluate Program Outcome (PO) attainment levels of graduating batches to identify academic or pedagogical gaps. If deficiencies are noted, targeted revisions are proposed to enhance student learning outcomes and ensure alignment with the desired graduate attributes.</p>
                                        
                                        <p>The process begins with each Area Chair leading the syllabus development with inputs from their respective faculty teams. The draft curriculum is then presented to the Area Academic Advisory Board, whose feedback is incorporated into the design. The revised curriculum is submitted to the Dean Academics for review, followed by scrutiny and final approval by the Director. Once approved, the updated curriculum is implemented across the program.</p>
