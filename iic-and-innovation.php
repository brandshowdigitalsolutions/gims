                                            <h3>About Institution's Innovation Council (IIC)</h3>
                                            <p>
                                                In the year 2018, the Ministry of Education (MoE) through MoE's
                                                Innovation Cell (MIC) launched the Institution's Innovation Council
                                                (IIC) program in collaboration with AICTE for Higher Educational
                                                Institutions (HEIs) to systematically foster the culture of innovation
                                                and start-up ecosystem in education institutions.
                                            </p>
                                            <p>
                                                Primarily, IICs' role is to engage large number of faculty, students and
                                                staff in various innovation and entrepreneurship related activities such
                                                as ideation, problem solving, proof of concept development, design
                                                thinking, IPR, project handling and management at
                                                Pre-incubation/Incubation stage, etc., so that innovation and
                                                entrepreneurship ecosystem gets established and stabilized in HEIs.
                                            </p>
                                            <p>
                                                The IIC model is designed to address challenges such as low leadership
                                                involvement, unplanned I&E activity planning, lack of synergy in
                                                resource mobilization, and underutilization of creative potential of
                                                youth.
