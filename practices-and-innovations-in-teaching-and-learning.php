            function toggleView(view) {
                var beyondDiv = document.getElementById("view-beyond");
                var aboutDiv = document.getElementById("view-about");
                var btnBeyond = document.getElementById("btn-beyond");
                var btnAbout = document.getElementById("btn-about");

                if (view === "about") {
                    beyondDiv.classList.add("hidden-content");
                    aboutDiv.classList.remove("hidden-content");

                    btnAbout.classList.add("active");
                    btnBeyond.classList.remove("active");

                    hideReadingOptions();
                    hideQuestionBank(); // reset QB also
                } else {
                    aboutDiv.classList.add("hidden-content");
                    beyondDiv.classList.remove("hidden-content");

                    btnBeyond.classList.add("active");
                    btnAbout.classList.remove("active");
                }
            }

            function showReadingOptions() {
                document.getElementById("about-level-1").classList.add("hidden-content");
                document.getElementById("about-level-2").classList.remove("hidden-content");
            }

            function hideReadingOptions() {
                var lvl1 = document.getElementById("about-level-1");
                var lvl2 = document.getElementById("about-level-2");

                if (lvl1 && lvl2) {
                    lvl1.classList.remove("hidden-content");
                    lvl2.classList.add("hidden-content");
                }
            }

