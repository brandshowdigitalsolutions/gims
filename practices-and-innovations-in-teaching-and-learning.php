            let selectedBatch = "";
            let selectedTrimester = "";

            function hideQuestionBank() {
                document.getElementById("qb-level-2").classList.add("hidden-content");
                document.getElementById("qb-level-3").classList.add("hidden-content");
                document.getElementById("qb-level-4").classList.add("hidden-content");
            }

            function showQuestionBankBatches() {
                hideReadingOptions();
                hideQuestionBank();
                document.getElementById("about-level-1").classList.add("hidden-content");
                document.getElementById("qb-level-2").classList.remove("hidden-content");
            }

            function showTrimesters(batch) {
                selectedBatch = batch;
                hideQuestionBank();

                document.getElementById("trimester-title").innerText = "Select Trimester – Batch " + batch;

                const buttons = document.getElementById("qb-level-3").querySelectorAll(".btn-academic");

                const available = questionBankData[batch] || {};

                buttons.forEach((btn, index) => {
                    const trimesterNo = index + 1;
                    btn.style.display = available[trimesterNo] ? "inline-block" : "none";
                });

                document.getElementById("qb-level-3").classList.remove("hidden-content");
            }

            function showPDFs(trimester) {
                hideQuestionBank();

                document.getElementById("pdf-title").innerText = "Batch " + selectedBatch + " | Trimester " + trimester;

                const container = document.getElementById("pdf-links");
                container.innerHTML = "";

                const data = questionBankData[selectedBatch] && questionBankData[selectedBatch][trimester];

                if (!data || data.length === 0) {
                    container.innerHTML = "<p style='color:red;font-weight:600;'>No Question Bank available.</p>";
                } else {
                    data.forEach((pdf) => {
                        const a = document.createElement("a");
                        a.href = pdf.link;
                        a.target = "_blank";
                        a.className = "btn-academic";
                        a.innerText = pdf.name;
                        container.appendChild(a);
                    });
                }

                document.getElementById("qb-level-4").classList.remove("hidden-content");
            }

